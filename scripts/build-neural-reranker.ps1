if ([string]::IsNullOrWhiteSpace($OutputDirectory)) {
    $OutputDirectory = Join-Path $repository 'artifacts\release'
}
if ([string]::IsNullOrWhiteSpace($WorkDirectory)) {
    $WorkDirectory = Join-Path $env:USERPROFILE 'tmp\sakura-input-neural-build'
}
$OutputDirectory = [IO.Path]::GetFullPath($OutputDirectory)
$WorkDirectory = [IO.Path]::GetFullPath($WorkDirectory)

$modelId = 'ku-nlp/deberta-v2-tiny-japanese-char-wwm'
$modelRevision = '41bcb8a393383a039c7ee18ded6893ca82e668b7'
$ortVersion = '1.28.0'
$ortArchiveHash = 'abef733dacbe2f571547a7150b479b5cb9cc0df22f96c24983a42cadb1b4f8bc'
$ortArchiveUrl = "https://github.com/microsoft/onnxruntime/releases/download/v$ortVersion/onnxruntime-win-x64-$ortVersion.zip"
