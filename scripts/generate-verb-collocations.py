#!/usr/bin/env python3
"""Regenerates data/verb-collocation-edges.tsv from data/verb-collocations.tsv (Issue #335).

The pair table lists noun + particle + verb collocations (窓を閉める, 雨が降る).
Each pair expands to one compound dictionary edge per verb form (reading =
noun + particle + verb form, surface likewise, left id = the noun's, right id =
the verb form's). A compound edge is a single lattice edge, so it prices the
whole collocation across the particle -- which no per-word cost can do. The
conversion lattice and the learning store are not touched.

Each edge is then priced so that its lattice total lands MARGIN below the best
competing path for the same reading, probed in the context a form can validly
take (the bare form plus a suffix such as て / ます / ない). MARGIN is the
homophone margin of data/conversion-priorities.tsv (Issue #94).

Subcommands (Python standard library only):

  plan    expand the pair table into unpriced edges and list the probe inputs
  update  one calibration round: read probe results, set or raise each price
  write   write the priced edges as data/verb-collocation-edges.tsv
  check   confirm a checked-in edge file is a priced subset of the expansion

Calibration loop (the probe converter is external to this repository; it must
convert each probe reading with the production options and print one JSON
object per line, see PROBE RESULT below):

  1. Build the dictionary WITHOUT data/verb-collocation-edges.tsv; keep its
     category directory (artifacts/release/カテゴリ辞書).
  2. plan --state s0.json --probes probes.tsv ...
  3. Convert probes.tsv with that dictionary -> results0.jsonl
     update --state s0.json --results results0.jsonl --out s1.json
  4. Repeat for ROUNDS (the checked-in file used 4): write s_i.json to the edge
     file, rebuild the dictionary with it, convert probes.tsv again, update.
  5. write --state s_final.json --out data/verb-collocation-edges.tsv

PROBE INPUT (probes.tsv, no header): id <TAB> reading <TAB> expected surface
PROBE RESULT (one line per probe):
  {"reading": str, "expected": str, "top": str,
   "cands": [{"t": surface, "cost": int}, ...],
   "forced": {surface: {"total": int}}}   # total path cost of that surface
"""
import argparse
import array
import collections
import json
import sys
from pathlib import Path

MARGIN = 60

# Godan row by final kana: (a, i, e, o, onbin) stems.
GODAN = {
    'う': 'わいえおっ', 'く': 'かきけこい', 'ぐ': 'がぎげごい', 'す': 'さしせそし',
    'つ': 'たちてとっ', 'ぬ': 'なにねのん', 'ぶ': 'ばびべぼん', 'む': 'まみめもん',
    'る': 'らりれろっ',
}
TE_FORMS = ['て', 'た', 'たら', 'てる', 'ている', 'てない']
CONTRACTED_TE_TAILS = ('てる', 'ている', 'てない', 'でる', 'でいる', 'でない')

EDGE_PREAMBLE = """\
# license: LicenseRef-Sakura-InHouse
# Generated by scripts/generate-verb-collocations.py from verb-collocations.tsv
# (Issue #335). Do not edit by hand: regenerate, or fix the pair table.
#
# Each row is one compound edge: noun + particle + verb form as a single lattice
# edge, so it prices a collocation across the particle (窓を閉めて) that no
# per-word cost can. Left id is the noun's, right id the verb form's. The cost
# is calibrated so the edge's lattice total lands 60 below the best competing
# path for the same reading -- the margin the homophone rows of
# conversion-priorities.tsv use -- which flips the top-1 and leaves the rest of
# the candidate page in its existing order. A form that already led keeps no row.
#
# Every row says nothing to the user: no prediction cost, no predict flag, an
# empty annotation. The `it` flag is copied from the noun so the IT bonus of the
# noun edge is not lost inside the compound.
"""
EDGE_HEADER = 'reading\tsurface\tleft_id\tright_id\tword_cost\tprediction_cost\tflags\tannotation'


def fail(message):
    sys.exit(f'generate-verb-collocations: {message}')


def read_connection(path):
    """Mozc connection matrix: first value is the dimension, then row-major costs."""
    values = array.array('i', map(int, Path(path).read_text(encoding='utf-8').split()))
    size = values[0]
    matrix = values[1:]
    if len(matrix) != size * size:
        fail(f'{path}: {len(matrix)} costs for dimension {size}')
    return size, matrix


def read_id_def(path):
    features = {}
    for line in Path(path).read_text(encoding='utf-8').splitlines():
        ident, _, rest = line.partition(' ')
        features[int(ident)] = rest.split(',')
    return features


def read_category_entries(directory):
    """reading -> [(surface, left, right, cost, flags)] over every category file."""
    by_reading = collections.defaultdict(list)
    for path in sorted(Path(directory).glob('*.tsv')):
        for line in path.read_text(encoding='utf-8').splitlines():
            if line.startswith('#') or line.startswith('reading\t'):
                continue
            f = line.split('\t')
            if len(f) < 5:
                continue
            by_reading[f[0]].append((f[1], int(f[2]), int(f[3]), int(f[4]),
                                     f[6] if len(f) > 6 else ''))
    return by_reading


def read_pairs(path):
    """Rows of data/verb-collocations.tsv in file order."""
    rows = []
    for number, line in enumerate(Path(path).read_text(encoding='utf-8').splitlines(), 1):
        if not line.strip() or line.startswith('#') or line.startswith('noun_reading\t'):
            continue
        f = line.split('\t')
        if len(f) != 5:
            fail(f'{path}:{number}: expected 5 tab-separated columns')
        row = tuple(f)  # noun_reading, noun_surface, particle, verb_reading, verb_surface
        if row in rows:
            fail(f'{path}:{number}: duplicate pair')
        rows.append(row)
    return rows


def form_tails(last, ichidan):
    """Kana tails appended to the verb stem; the stem is the dictionary form minus its last kana."""
    if ichidan:
        return ['', 'る'] + TE_FORMS + ['ます', 'ました', 'たい', 'ない', 'なかった']
    a, i, e, o, onbin = GODAN[last]
    tails = [a, i, e, o, onbin, last]
    tails += [onbin + x for x in TE_FORMS]
    tails += [i + x for x in ['ます', 'ました', 'たい']]
    tails += [a + x for x in ['ない', 'なかった']]
    if last in 'ぐぬぶむ':
        # voiced onbin: ん + で / だ
        tails = [x for x in tails if not x.startswith((onbin + 'て', onbin + 'た'))]
        tails += [onbin + x.replace('て', 'で').replace('た', 'だ') for x in TE_FORMS]
    return tails


def expand(pairs, by_reading, features, size, matrix):
    """Unpriced edges: price `w0` is the natural path cost noun + particle + verb form."""
    def connection(right_id, left_id):
        return matrix[right_id * size + left_id]

    verb_forms = {}

    def forms_of(verb_reading, verb_surface):
        key = (verb_reading, verb_surface)
        if key not in verb_forms:
            lemma = [e for e in by_reading.get(verb_reading, [])
                     if e[0] == verb_surface and features[e[1]][0] == '動詞'
                     and features[e[1]][5] == '基本形']
            if not lemma:
                fail(f'verb not in the dictionary: {verb_reading} {verb_surface}')
            ichidan = features[lemma[0][1]][4] == '一段'
            stem_reading, stem_surface = verb_reading[:-1], verb_surface[:-1]
            forms = []
            for tail in form_tails(verb_reading[-1], ichidan):
                for surface, left, right, cost, _ in by_reading.get(stem_reading + tail, []):
                    # Every verb form has one id on both sides except the
                    # contracted てる / ている / てない forms, which connect
                    # through their auxiliary's right id (Issue #334).
                    if surface != stem_surface + tail:
                        continue
                    if left != right and not tail.endswith(CONTRACTED_TE_TAILS):
                        continue
                    pos = features[left]
                    if pos[0] != '動詞' or (pos[4] == '一段') != ichidan:
                        continue
                    forms.append((tail, surface, left, right, cost))
            verb_forms[key] = (ichidan, verb_reading[-1], stem_reading, forms)
        return verb_forms[key]

    rows = []
    for noun_reading, noun_surface, particle, verb_reading, verb_surface in pairs:
        ichidan, last, stem_reading, forms = forms_of(verb_reading, verb_surface)
        nouns = sorted((e for e in by_reading.get(noun_reading, [])
                        if e[0] == noun_surface and (features[e[1]][0] == '名詞' or not particle)),
                       key=lambda e: e[3])[:8]
        if not nouns:
            fail(f'noun not in the dictionary: {noun_reading} {noun_surface}')
        if particle:
            particles = [e for e in by_reading.get(particle, [])
                         if e[0] == particle and features[e[1]][0] == '助詞']
            if not particles:
                fail(f'particle not in the dictionary: {particle}')
        for _, noun_left, noun_right, noun_cost, noun_flags in nouns:
            for tail, surface, left, right, cost in forms:
                if particle:
                    between = min((connection(noun_right, p[1]) + p[3] + connection(p[2], left), p)
                                  for p in particles)[0]
                else:
                    between = connection(noun_right, left)
                rows.append({
                    'reading': noun_reading + particle + stem_reading + tail,
                    'surface': noun_surface + particle + surface,
                    'l': noun_left, 'r': right,
                    'w0': noun_cost + between + cost,
                    'tail': tail, 'vlast': last, 'ichidan': ichidan,
                    'flags': 'it' if 'it' in noun_flags.split(',') else '',
                })
    return rows


def probe_suffixes(row):
    """Kana suffixes that validly follow this form; '' is the bare probe."""
    suffixes = ['']
    if row['ichidan']:
        if row['tail'] == '':
            suffixes += ['て', 'ます', 'ない']
    else:
        a, i, e, _, onbin = GODAN[row['vlast']]
        if row['tail'] == a:
            suffixes += ['ない']
        elif row['tail'] == i:
            suffixes += ['ます']
        elif row['tail'] == e:
            suffixes += ['ば']
        elif row['tail'] == onbin:
            suffixes += ['て']
    return suffixes


def keep_cheapest(rows):
    """One edge per (reading, surface, left, right); the cheapest price wins, first position kept."""
    best = {}
    for row in rows:
        key = (row['reading'], row['surface'], row['l'], row['r'])
        if key not in best or row['w'] < best[key]['w']:
            best[key] = row
    return list(best.values())


def calibrate(rows, results):
    """One round. Rows without `B` are unpriced: drop those already top-ranked, price the rest.
    Rows with `B` are raised by the shortfall of every probe that still does not top-rank."""
    probes = {}
    for line in Path(results).read_text(encoding='utf-8').splitlines():
        d = json.loads(line)
        probes[(d['reading'], d['expected'])] = d
    kept = []
    for row in rows:
        shortfalls = []
        failed = False
        for suffix in row['sufs']:
            d = probes[(row['reading'] + suffix, row['surface'] + suffix)]
            expected = row['surface'] + suffix
            cost = next((c['cost'] for c in d['cands'] if c['t'] == expected), None)
            if cost is None:
                forced = d['forced'].get(expected)
                cost = forced['total'] if forced else None
            others = [c['cost'] for c in d['cands'] if c['t'] != expected]
            if cost is None or not others:
                continue
            missed = d['top'] != expected
            failed = failed or missed
            shortfalls.append((missed, cost - min(others) + MARGIN))
        if 'B' not in row:
            if not failed:
                continue
            row['B'] = max(0, max(need for _, need in shortfalls))
        else:
            bad = [need for missed, need in shortfalls if missed]
            if bad:
                row['B'] += max(max(bad), 1)
        row['w'] = row['w0'] - row['B']
        kept.append(row)
    return keep_cheapest(kept)


def edge_lines(rows):
    return [f"{r['reading']}\t{r['surface']}\t{r['l']}\t{r['r']}\t{r['w']}\t-\t{r['flags']}\t"
            for r in rows]


def command_plan(args):
    size, matrix = read_connection(args.connection)
    rows = expand(read_pairs(args.pairs), read_category_entries(args.categories),
                  read_id_def(args.id_def), size, matrix)
    probes = {}
    for row in rows:
        row['sufs'] = probe_suffixes(row)
        for suffix in row['sufs']:
            probes.setdefault((row['reading'] + suffix, row['surface'] + suffix), len(probes))
    Path(args.state).write_text(json.dumps(rows, ensure_ascii=False), encoding='utf-8')
    with open(args.probes, 'w', encoding='utf-8', newline='\n') as out:
        for (reading, surface), index in probes.items():
            out.write(f'p{index}\t{reading}\t{surface}\n')
    print(f'{len(rows)} unpriced edges, {len(probes)} probes')


def command_update(args):
    rows = json.loads(Path(args.state).read_text(encoding='utf-8'))
    updated = calibrate(rows, args.results)
    Path(args.out).write_text(json.dumps(updated, ensure_ascii=False), encoding='utf-8')
    print(f'{len(updated)} priced edges')


def command_write(args):
    rows = json.loads(Path(args.state).read_text(encoding='utf-8'))
    if any('B' not in r for r in rows):
        fail('state still holds unpriced edges; run update first')
    body = '\n'.join(edge_lines(rows))
    with open(args.out, 'w', encoding='utf-8', newline='\n') as out:
        out.write(f'{EDGE_PREAMBLE}{EDGE_HEADER}\n{body}\n')
    print(f'{len(rows)} edges -> {args.out}')


def command_check(args):
    size, matrix = read_connection(args.connection)
    rows = expand(read_pairs(args.pairs), read_category_entries(args.categories),
                  read_id_def(args.id_def), size, matrix)
    natural = {(r['reading'], r['surface'], r['l'], r['r']): r['w0'] for r in rows}
    problems = []
    count = 0
    for line in Path(args.edges).read_text(encoding='utf-8').splitlines():
        if line.startswith('#') or line.startswith('reading\t') or not line.strip():
            continue
        f = line.split('\t')
        count += 1
        key = (f[0], f[1], int(f[2]), int(f[3]))
        if key not in natural:
            problems.append(f'not produced by the pair table: {key}')
        elif int(f[4]) > natural[key]:
            problems.append(f'priced above its natural cost {natural[key]}: {key}')
    if problems:
        fail(f'{len(problems)} problems, first: {problems[0]}')
    print(f'{count} edges are priced edges of the {len(natural)}-edge expansion')


def main():
    root = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = root.add_subparsers(dest='command', required=True)

    def inputs(p):
        p.add_argument('--pairs', required=True, help='data/verb-collocations.tsv')
        p.add_argument('--categories', required=True, help='category dictionary directory')
        p.add_argument('--connection', required=True, help='Mozc connection_single_column.txt')
        p.add_argument('--id-def', required=True, help='Mozc id.def')

    p = commands.add_parser('plan')
    inputs(p)
    p.add_argument('--state', required=True)
    p.add_argument('--probes', required=True)
    p.set_defaults(run=command_plan)
    p = commands.add_parser('update')
    p.add_argument('--state', required=True)
    p.add_argument('--results', required=True)
    p.add_argument('--out', required=True)
    p.set_defaults(run=command_update)
    p = commands.add_parser('write')
    p.add_argument('--state', required=True)
    p.add_argument('--out', required=True)
    p.set_defaults(run=command_write)
    p = commands.add_parser('check')
    inputs(p)
    p.add_argument('--edges', required=True, help='data/verb-collocation-edges.tsv')
    p.set_defaults(run=command_check)

    args = root.parse_args()
    args.run(args)


if __name__ == '__main__':
    main()
